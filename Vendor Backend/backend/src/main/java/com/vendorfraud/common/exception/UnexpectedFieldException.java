package com.vendorfraud.common.exception;

/**
 * The client supplied a field it is never allowed to control - an
 * approver id, a maker id, a reference, or a status. HTTP 400.
 */
public class UnexpectedFieldException extends RuntimeException {
    public UnexpectedFieldException(String field) {
        super("Field '" + field + "' is generated by the server and must not be supplied by the client");
    }
}
